const assert=require('node:assert/strict');
const G=require('../dist/engine.js');
const ids=s=>G.options(s).map(o=>o.id);
let s=G.create({origin:'merchant'});s.location='market';s.silver=100;
assert.ok(G.available(s).some(o=>o.id==='buymanual'));
