assert.ok(!G.available(s).some(o=>o.id==='buymanual'));
const silver=s.silver;s=G.step(s,'action:buymanual',()=>0);assert.equal(s.silver,silver);
s.pending='mentor';assert.ok(ids(s).includes('serve'));assert.ok(ids(s).includes('guidance'));
s.flags.mentor=true;assert.ok(!ids(s).includes('serve'));assert.ok(ids(s).includes('guidance'));
s.manuals.push(2);assert.ok(!ids(s).includes('guidance'));assert.ok(ids(s).includes('depart'));
